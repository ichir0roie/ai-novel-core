# 「◇」で場面を切る約束をやめ、行の組み方は本文の行に持つ(コードの EPISODE_LAYOUT_INSTRUCTION にあった文面)
_LAYOUT = """\
行の組み方:
場面の切れ目には、空行を二つ置く。
セリフは、中に文がいくつあっても「」ごと一行にする(長い行は清書のときに折り返される)。
一人の人物の言動が続くあいだは、セリフと地の文を、空行を挟まず改行だけで続ける。
空行は、話し手や流れが変わるところにだけ一つ置き、ほかでは空けない。"""


def _joined(texts) -> str:
    return "\n\n".join(text.strip() for text in texts if text and text.strip())


def _move_rows() -> None:
    """範囲がストーリーの行は作品の instruction へ移し、残りは範囲ごとに一行(id の順につなぎ、一番小さい id に残す)にする。"""
    bind = op.get_bind()
    rows = bind.execute(sa.text("SELECT id, scope, story_id, text FROM style_preference ORDER BY id")).all()
    by_story: dict[int, list[str]] = {}
    by_scope: dict[str, list] = {}
    for row in rows:
        if row.scope == 'ストーリー':
            by_story.setdefault(row.story_id, []).append(row.text)
        else:
            by_scope.setdefault(row.scope, []).append(row)
    for story_id, texts in by_story.items():
        bind.execute(sa.text("UPDATE story SET instruction = :text WHERE id = :id"), {"id": story_id, "text": _joined(texts)})
    bind.execute(sa.text("DELETE FROM style_preference WHERE scope = 'ストーリー'"))
    for scope, scope_rows in by_scope.items():
        texts = [row.text for row in scope_rows]
        if scope == '本文' and _LAYOUT not in texts:
            texts.append(_LAYOUT)
        keep, *rest = scope_rows
        bind.execute(sa.text("UPDATE style_preference SET text = :text WHERE id = :id"), {"id": keep.id, "text": _joined(texts)})
        for row in rest:
            bind.execute(sa.text("DELETE FROM style_preference WHERE id = :id"), {"id": row.id})
    _add_moved_instructions(bind, set(by_scope))


# コードから範囲の行へ移した段落の書き出し。既にある全体・本文の行には、これらの段落だけを末尾に足す
_MOVED_HEADS = ("生物・医療・兵器", "人物の年齢は", "名づけ:", "「名前だけ出る人物」", "渡す設定(アイデア)", "「文体の見本」")


def _add_moved_instructions(bind, scopes: set[str]) -> None:
    """コードにあった AI への指示を行にする。範囲の行が無ければ初期値を足し、あれば移した段落だけを足す。
    仕事ごとの指示の行は、無ければ足す。"""
    from db.style_defaults import DEFAULT_INSTRUCTIONS, DEFAULT_STYLE_PREFERENCES

    for scope, text in DEFAULT_STYLE_PREFERENCES:
        if scope not in scopes:
            bind.execute(sa.text("INSERT INTO style_preference (scope, text) VALUES (:scope, :text)"),
                         {"scope": scope, "text": text})
            continue
        current = bind.execute(sa.text("SELECT text FROM style_preference WHERE scope = :scope"), {"scope": scope}).scalar()
        moved = [part for part in text.split("\n\n") if part.startswith(_MOVED_HEADS) and part not in current]
        if moved:
            bind.execute(sa.text("UPDATE style_preference SET text = :text WHERE scope = :scope"),
                         {"scope": scope, "text": _joined([current, *moved])})
    for scope, text in DEFAULT_INSTRUCTIONS:
        if scope not in scopes:
            bind.execute(sa.text("INSERT INTO style_preference (scope, text) VALUES (:scope, :text)"),
                         {"scope": scope, "text": text})


