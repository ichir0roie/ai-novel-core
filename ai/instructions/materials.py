from __future__ import annotations

# 人物を時点つきで渡すすべての生成と、このセッションの Claude が書く本文の材料に足す
TIME_NOTE = """\
人物の年齢は、この時点での歳。来歴は、この時点までに起きた節目だけを渡す。
ただし人物像は時期を限らない説明で、その人物の後年の立場・仕事・住まい・人間関係を含むことがあり、この時点ではまだ手にしていないことがある。
来歴の年と年齢から、この時点でその人物がどの段階にいるか(子どもの頃・見習い・一人前・老境など)を先に見極め、その歳の者にできること・置かれうる立場に合った出来事と振る舞いにする。
後年の立場を先取りしない。性格・癖・口調は、その歳らしい現れ方にする。"""

SAFETY_NOTE = """\
生物・医療・兵器(病原体・毒物・薬品・兵器)に関わる内容は、物語に要る抽象度にとどめる。
- 実在の病原体・毒物の名前と、作り方・手順・条件・分量・入手方法は書かない。
- 性質は「致死性の高い」程度の形容、仕組みは比喩か、人物が理解している程度で書く。
- 書くのは、何が起きたか・人がどう受け止め、どう動いたか・結果と影響まで。"""

# `generate` がどの生成の system にも足す
COMMON_NOTES = f"{TIME_NOTE}\n\n{SAFETY_NOTE}"

# 出来事を起こす・記録する材料の、居合わせる人物・対象(当事者)の読み方
EVENT_PARTICIPANT_NOTE = """\
居合わせる人物・対象(当事者)の読み方:
- 種別が「人物」以外なら、国・組織・集団・物。年齢は人物なら歳、それ以外は成立からの年数。
- 関係はその時点で続いている相関、直近の出来事はその者自身が場所を問わず関わった直近の出来事の名前。
- 性格の各軸は 無/低/並/高/必 の五段階。
「この時点より後に既に決まっている出来事」は、これと矛盾させず、そこで起きることを先回りして起こさない。"""

# 材料の「名前だけ出る人物」(プロット・本文に名前が出るだけの既知の人物)
MENTIONED_NOTE = """\
「名前だけ出る人物」は登場人物ではなく、プロット・本文に名前が出るだけの既知の人物。
話題・回想・噂などで触れるときは、年齢・種別・口調・人物像をその設定と食い違わせない。
プロット・本文が求めない限り、場面には出さない。"""

# 材料の設定(アイデア)と、場所・時代ごとの呼び名(履歴)
IDEA_NOTE = """\
渡す設定(アイデア)は世界の設定資料で、作中の人物がそのまま知っているとは限らない。
- 設定と矛盾させない。
- 各設定の「名前」は、この場所・時代での作中の呼び名(履歴に呼び名があればその名前、無ければ設定そのものの名前)。
  「作中での受け止め方」が null でない名前は、この場所・時代の人物が使い・知っているものとして、本文ではこの名で呼ぶ。
- 設定の仕組みや由来(「内容」)は、渡されていても地の文・セリフで説明しない。作中の人物が知りうる言葉と、表に出る様子(症状・しぐさ・道具の使われ方・噂)だけで書き、仕組みを推し量って書き足さない。"""

