"""出来事(`Event`)の書き方・進め方のルールを持つ、正本。

Claude が `CommitEvent` の `text` を書くときも、`GenerateEvent` が
`data_access_logic/event/progress.py` で出来事を生成するときも、ここに書いた定数の文面をそのまま基準にする。

出来事の `text` は小説ではなく、誰が何をして何を言ったかを整理した要約。実際のストーリー
(本文)は話(`Episode`)の側で別に書くので、出来事で文体・セリフの言い回しを決めない。
ルールの文面を変えるときはここだけを直す。
"""
from __future__ import annotations

from ai.instructions.naming import NAME_PLACEHOLDER

# 出来事を考えるとき、判断材料として渡す「直近の出来事」の件数
# (場所ごと・人物ごと・筋書きごとの三つの窓すべてに使う)。
# 増やすほど過去の語彙が持ち越され、自己増殖しやすくなる一方、
# 少なすぎると同じ展開が場所・人物を変えて繰り返されているのを
# 見分ける材料が足りなくなる(「同じ出来事を名前だけ変えて繰り返さない」
# 2026-09 の観測)。どちらのリスクも残ったままの折衷値として置く。
RECENT_EVENT_LIMIT = 5

# 人物の text に追記できる件数(生成時の基礎説明1件 + ここで数える追記件数)。
# 上限が無いと、一度紛れ込んだ語彙が将来の生成へ永久に持ち込まれ続ける。
CHARACTER_NOTE_LIMIT = 5
CHARACTER_NOTE_SEPARATOR = "\n---\n"

EVENT_RECORD_INSTRUCTION = """\
text は物語ではなく、この出来事で誰が何をして何を言ったかを整理した要約として書く。
情景描写・比喩・心の中の描写・語り口は書かない。
起きた順に、一行に一件ずつ、人物・対象それぞれを主語に立てて書く。
行動は、誰が、誰(どの対象)に対して、何を使って、具体的に何をしたか。
言動は、誰が誰に何を言ったか(求めた・断った・約束した・明かした・責めたなど)を要旨で書く。
最後の一〜二行に、その結果、前と後で何がどう変わったか(立場・所属・取り決め・資源の量・力関係・居場所など)を書く。
きっかけには、渡された場所・環境・資源・産業・人間関係・地名のうち少なくとも一つを名指しで使う。
数・期間・物の名前・場所の名前・人物の名前を書き込む。
実際に取った行動(要求した物の名前、動かした資源の量、出した命令の中身、移った先の場所など)を書く。
全体で10行程度にまとめる。
"""


# 人物の text は生涯を通した説明なので、来歴に書かれた後年の役職・出来事まで含む。
# 歳を渡すだけではそれを先取りした出来事になる(2026-09 の観測。十一歳の人物が関所の役人として勤めていた)。
EVENT_AGE_INSTRUCTION = """\
人物の年齢は、この時点での歳。人物像はその人物の生涯を通した説明で、来歴などに書かれた後年の立場・仕事・住まい・人間関係は、この時点ではまだ手にしていないことがある。
来歴の年と年齢から、この時点でその人物がどの段階にいるか(子どもの頃・見習い・一人前・老境など)を先に見極め、その歳の者にできること・置かれうる立場に合った出来事と振る舞いにする。
後年の立場を先取りしない。性格・癖・口調は、その歳らしい現れ方にする。"""

EVENT_PROGRESSION_INSTRUCTION = """\
この場所の直近の出来事の一覧(名前)を見て検討する。
人物・対象ごとに渡す直近の出来事(その者自身が場所を問わず関わった直近の出来事)と、
筋書きに関わる直近の出来事(この場所と、その上位の場所で直近使われた出来事の名前)もみる。
同じ形容表現を繰り返し出来事の軸に据えない。"""

