#!/usr/bin/env python3
"""出来事(`Event`)の書き方・進め方のルールを持つ、正本。

Claude が `CommitEvent` の `text` を書くときも、`GenerateEvent` が
`data_access_logic/event/progress.py` で出来事を
生成するときも、**ここに書いた定数の文面をそのまま基準にする。**

**出来事の `text` は小説ではなく、情報整理のための記録。** 実際のストーリー
(本文)は話(`Episode`)の側で別に書くので、出来事で文体・セリフの言い回しを
決めない。出来事が持つのは、物事がどう変わったか・人物が何を感じたか・誰と
どの組織が何をしたか、という後から引ける中身だけ。
ただし AI に起こさせた出来事(`GenerateEvent`)だけは、記録として
起こしたあと、`EVENT_NOVEL_INSTRUCTION` で話と同じ小説の形に書き直す(`data_access_logic/event/novelist.py`)。
**ルールの文面を変えるときはここだけを直す。**
"""
from __future__ import annotations

from ai.instructions import style
from ai.instructions.naming import NAME_PLACEHOLDER
from ai.instructions.style import EVENT_NOVEL_TARGET_LETTERS

# 出来事を考えるとき、判断材料として渡す「直近の出来事」の件数
# (場所ごと・人物ごと・筋書きごとの三つの窓すべてに使う)。
# 増やすほど過去の語彙が持ち越され、自己増殖しやすくなる一方、
# 少なすぎると同じ展開が場所・人物を変えて繰り返されているのを
# 見分ける材料が足りなくなる(「同じ出来事を名前だけ変えて繰り返さない」
# 2026-09 の観測)。どちらのリスクも残ったままの折衷値として置く。
RECENT_EVENT_LIMIT = 5

# 人物の text に追記できる件数(生成時の基礎説明1件 + ここで数える追記件数)。
# 上限が無いと、一度紛れ込んだ語彙が将来の生成へ永久に持ち込まれ続ける。
CHARACTER_NOTE_LIMIT = 5
CHARACTER_NOTE_SEPARATOR = "\n---\n"

EVENT_RECORD_INSTRUCTION = """\
text は小説ではなく、世界に何が起きて何が変わったかを後から引くための記録として書く。
情景描写・比喩・セリフ・語り口は書かない。
誰がどんな言い回しで喋ったかは本文(ストーリー)の側で決めるので、ここでは決めない。
書くのは、この出来事で新しく起きた事象だけ。
誰が、誰(どの対象)に対して、何を使って、具体的に何をしたか。
相手はそれにどう応じたか。
関わった人物が何に対してどう感じ、何を望み、何を恐れたか。
その結果、前と後で何がどう変わったか(立場・所属・取り決め・資源の量・力関係・居場所など)と、そのうち何がこの先も残るか。
これらを事実として、改行で区切った短い段落で書く。
きっかけには、渡された場所・環境・資源・産業・人間関係・地名のうち少なくとも一つを名指しで使い、行動は人物・対象それぞれを主語に立てて一件ずつ分けて書く。
分かるところは、数・期間・物の名前・場所の名前・人物の名前を具体的に書き込む。
状況を雰囲気で漂わせず、事実と関係で書く。
「対応を迫られた」「立場を守る行動をとった」「新たな局面を迎えた」のように何をしたかが分からない抽象的な言い回しは使わず、実際に取った行動(要求した物の名前、動かした資源の量、出した命令の中身、移った先の場所など)を書く。
次のものは text に入れない。
- 出来事の名前(event_name)やその言い換え。
- 「発端」「行動」「感情」「変化と影響」のような見出し・ラベル・番号付きの項目名。
- 渡された直近の出来事の名前を写した文や、過去の出来事の内容の要約・振り返り(過去の経緯は、必要なら一文で触れるだけにする)。
- 人物・対象・場所の text に既に書いてある説明の写し。
- 同じ内容を言い方を変えて二度書くこと。
全体で400〜800文字程度。"""

_EVENT_NOVEL_BODY = f"""\
text は、渡された出来事の記録を、話(episode)と同じ小説の本文に書き起こしたもの。\
{EVENT_NOVEL_TARGET_LETTERS[0]}〜{EVENT_NOVEL_TARGET_LETTERS[1]}字で書く。
記録の筋から外れず、記録に無い出来事を足さない。
場面で実際に起きる会話・動作・やりとりを省いて要約せず、場面を最後まで書き切って字数の目安を下回らない。
主役を視点人物に置き、主役の直前の出来事が終わった後の場面から書き始める。直前の出来事の中身をなぞり直さない。
記録に書かれた変化(立場・取り決め・居場所など)は、説明の地の文でまとめず、人物の言動と、視点人物が見聞きしたものとして書く。
人物は名前で書き、口調・方言・一人称・二人称は渡された人物の情報に合わせる。
見出し・番号・出来事の名前の写しは入れない。"""


def event_novel_instruction(*, shared_style_extra: str = "", style_extra: str = "") -> str:
    """出来事の本文(`GenerateEvent` の小説化)の指示。文体の好み(`shared_style_extra` / `style_extra`。
    世界の舞台設定・既存の話から抽出した文体の癖など)は呼び出し側(親リポジトリ側)から渡す。"""
    return (f"{_EVENT_NOVEL_BODY}\n"
            f"{style.style_instruction('event_novel', shared_extra=shared_style_extra, extra=style_extra)}")


# 文体の好みを渡さない既定の文面(そのまま使う呼び出し・テスト用)。
EVENT_NOVEL_INSTRUCTION = event_novel_instruction()

# 人物の text は生涯を通した説明なので、来歴に書かれた後年の役職・出来事まで含む。
# 歳を渡すだけではそれを先取りした出来事になる(2026-09 の観測。十一歳の人物が関所の役人として勤めていた)。
EVENT_AGE_INSTRUCTION = """\
人物の年齢は、この時点での歳。人物像はその人物の生涯を通した説明で、来歴などに書かれた後年の立場・仕事・住まい・人間関係は、この時点ではまだ手にしていないことがある。
来歴の年と年齢から、この時点でその人物がどの段階にいるか(子どもの頃・見習い・一人前・老境など)を先に見極め、その歳の者にできること・置かれうる立場に合った出来事と振る舞いにする。
後年の立場を先取りしない。性格・癖・口調は、その歳らしい現れ方にする。"""

EVENT_PROGRESSION_INSTRUCTION = """\
この場所の直近の出来事の一覧(名前)を見て検討する。
人物・対象ごとに渡す直近の出来事(その者自身が場所を問わず関わった直近の出来事)と、
筋書きに関わる直近の出来事(この場所と、その上位の場所で直近使われた出来事の名前)もみる。
同じ形容表現を繰り返し出来事の軸に据えない。"""

# event_duration_days キーの説明文。キー名は使う側が付ける。
EVENT_DURATION_INSTRUCTION = (
    "この出来事の影響が続く日数の整数。関わった人物・対象は、この日数のあいだ進行中として次の出来事の対象から外れる。"
    "立ち話や単発の判断なら1、旅・対立の膠着・準備のように長く尾を引くものなら30〜90程度など、内容に見合う値を1〜90の範囲で決める。"
)

CHARACTER_TEXT_UPDATE_INSTRUCTION = f"""\
text は、この出来事を通して見えた、その人物の性格・信念・人となり(パーソナリティ。人物以外の対象なら性質・方針・立場)についてだけ短く一言で書く。
状況の要約や、その場の立場・置かれている状態は書かない。
この出来事でそれについて新しく分かったことが無ければ、この人物自体を character_updates に含めない。
既存の text で既に使われている単語・言い回しをそのまま繰り返さない。
書いた内容は既存の text の続きに積み足されるので、それだけで意味が通る一文にする。
この人物自身を指すときは名前を書かず、必ず「{NAME_PLACEHOLDER}」とだけ書く。"""
